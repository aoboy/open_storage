def prometheus_rules() -> dict[str, object]:
    """Build a Prometheus rule-file document from the executable specs."""
    rules: list[dict[str, object]] = []
    severities: tuple[Severity, Severity] = ("warning", "page")
    for spec in ALERT_SPECS:
        for severity in severities:
            threshold = spec.threshold(severity)
            expr = spec.expr.replace("{threshold}", format(threshold, ".17g"))
            rules.append(
                {
                    "alert": f"Sdf{spec.name}{severity.title()}",
                    "expr": expr,
                    "for": spec.warning_for if severity == "warning" else spec.page_for,
                    "labels": {"severity": severity, "component": "sdf"},
                    "annotations": {
                        "summary": spec.summary,
                        "threshold": format(threshold, ".17g"),
                    },
                }
            )
    return {"groups": [{"name": "sdf-rollout-guardrails", "rules": rules}]}


def render_rules() -> str:
    header = "# Generated by sdf.common.alerts; edit ALERT_SPECS, not this file.\n"
    return header + str(yaml.safe_dump(prometheus_rules(), sort_keys=False))


def write_rules(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_rules(), encoding="utf-8")


def main() -> None:
    """Regenerate the checked-in Prometheus rule file."""
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "output",
        nargs="?",
        type=Path,
        default=Path("docs/ops/alerts/sdf-alerts.yml"),
    )
    args = parser.parse_args()
    write_rules(args.output)


if __name__ == "__main__":
    main()
